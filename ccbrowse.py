# noise wrappers that make a first prompt unreadable as a title
_STRIP_BLOCKS = re.compile(
    r"<(system-reminder|local-command-stdout|command-args|command-contents)>.*?</\1>",
    re.S,
)
_CMD_NAME = re.compile(r"<command-name>\s*(.*?)\s*</command-name>", re.S)
_CMD_MSG = re.compile(r"</?command-message>", re.S)
_ANY_TAG = re.compile(r"<[^>]{1,60}>")
# a wrapper with attributes blows past the 60-char cap above — subagent prompts
# arrive inside one of these, so the tag would otherwise become the title
_ATTR_TAG = re.compile(r"</?[a-zA-Z][\w-]*(?:\s+[\w-]+=\"[^\"]*\")*\s*/?>")
# claude code prepends this to messages produced by local command output
_CAVEAT = re.compile(
    r"Caveat: The messages below were generated by the user while running local"
    r" commands\. DO NOT.*?(?=$|\n)",
    re.S,
)
# a message from another claude session is delivered as a plain `type=user`
# line whose metadata is byte-identical to a typed prompt — no isMeta, no
# marker field. the wrapper around the payload is the only signal there is.
_INBOUND = re.compile(
    r"<(teammate|agent|cross-session)-message\b([^>]*)>(.*?)</\1-message>", re.S
)
_INBOUND_HEAD = re.compile(r"^\s*(?:Another Claude session sent a message:\s*)?<")
_INBOUND_ATTR = re.compile(r"([\w-]+)=\"([^\"]*)\"")
# the attributes the three wrapper flavours name their sender with, best first
_SENDER_KEYS = ("teammate_id", "from-name", "from", "name")


def inbound_message(text: str) -> tuple[str, str] | None:
    """(sender, payload) when a user turn is really a message from another session.

    None for anything typed by the actual user. The wrapper has to open the
    message — a quoted one further down is somebody talking *about* a teammate
    message, not one being delivered.
    """
    if not text or "-message" not in text:
        return None
    if not _INBOUND_HEAD.match(text):
        return None
    parts = list(_INBOUND.finditer(text))
    if not parts:
        return None
    if parts[0].start() > 60:  # only the one boilerplate line may precede it
        return None
    attrs = dict(_INBOUND_ATTR.findall(parts[0].group(2)))
    sender = next(
        (attrs[k] for k in _SENDER_KEYS if attrs.get(k)), "another claude session"
    )
    payload = "\n\n".join(p.group(3).strip() for p in parts if p.group(3).strip())
    return sender, payload


def clean_prompt(text: str) -> str:
    """turn a raw first user message into something readable as a title."""
    if not text:
        return ""
    text = _CAVEAT.sub(" ", text)
    cmd = _CMD_NAME.search(text)
    body = _STRIP_BLOCKS.sub(" ", text)
    body = _CMD_MSG.sub(" ", body)
    body = _ATTR_TAG.sub(" ", body)
    body = _ANY_TAG.sub(" ", body)
    body = re.sub(r"\s+", " ", body).strip()
    if cmd:
        name = cmd.group(1)
        # a slash command with no extra prose is more useful shown as the command
        return f"{name} {body}".strip() if body and body != name else name
    return body


def block_text(block: dict) -> tuple[str, str]:
    """(kind, text) for one assistant/user content block."""
    kind = block.get("type")
    if kind == "text":
        return "text", block.get("text", "")
    if kind == "thinking":
        return "thinking", block.get("thinking", "")
    if kind == "tool_use":
        name = block.get("name", "tool")
        inp = block.get("input", {})
        if isinstance(inp, dict):
            hint = (
                inp.get("command")
                or inp.get("file_path")
                or inp.get("pattern")
                or inp.get("prompt")
                or inp.get("description")
                or ""
            )
        else:
            hint = str(inp)
        return "tool", f"{name}: {str(hint)[:200]}"
    if kind == "tool_result":
        content = block.get("content", "")
        if isinstance(content, list):
            content = " ".join(
                c.get("text", "") for c in content if isinstance(c, dict)
            )
        return "tool_result", str(content)
    if kind == "image":
        return "image", "[image]"
    return kind or "unknown", ""


def message_blocks(msg: dict) -> list[tuple[str, str, dict]]:
    """(kind, text, raw block) for every content block of a message."""
    content = msg.get("content")
    if isinstance(content, str):
        return [("text", content, {})]
    if isinstance(content, list):
        return [(*block_text(b), b) for b in content if isinstance(b, dict)]
    return []


def message_parts(msg: dict) -> list[tuple[str, str]]:
    return [(k, t) for k, t, _ in message_blocks(msg)]


def file_identity(path: Path) -> tuple[str, str, str, str]:
    """(kind, session_id, parent_id, agent_id) implied by a log's location.

    top-level logs are `<project>/<uuid>.jsonl`; anything deeper is a subagent
    transcript living under `<project>/<owning-uuid>/subagents/...`. subagent
    files carry the *owning session's* id in their own `sessionId` field, so the
    row id has to come from the path or every subagent would collide with it.

    `rel[1]` is the owning session at any nesting depth: a subagent that spawns
    its own subagents does not get a directory of its own — everything it
    spawns is written flat into the same session-level `subagents/` tree — so
    this resolves to the top-level session rather than to an intermediate
    agent. (`parent_agent_id` from the sidecar records the immediate spawner.)
    """
    try:
        rel = path.relative_to(PROJECTS).parts
    except ValueError:
        return "session", path.stem, "", ""
    if len(rel) <= 2:
        return "session", path.stem, "", ""
    parent = rel[1]
    tail = "~".join(rel[2:])[: -len(".jsonl")] if path.suffix == ".jsonl" else "~".join(rel[2:])
    agent = path.stem[len("agent-"):] if path.stem.startswith("agent-") else path.stem
    return "subagent", f"{parent}~{tail}", parent, agent


def read_sidecar(path: Path) -> dict:
    """`<transcript>.meta.json` — what the harness knew when it spawned the agent.

    two thirds of transcripts have one. `description` is a human-written
    one-liner, so it beats anything inferable from the first message, and
    `toolUseId` is the spawning Task call stated outright rather than
    reconstructed from the parent log.
    """
    side = path.with_name(path.stem + ".meta.json")
    try:
        d = json.loads(side.read_text(encoding="utf-8", errors="replace"))
    except (OSError, json.JSONDecodeError):
        return {}
    return d if isinstance(d, dict) else {}


def scan_file(path_str: str) -> dict | None:
    """single pass over one session file, extracting index metadata + search text."""
    path = Path(path_str)
    try:
        st = path.stat()
    except OSError:
        return None

    kind_of_file, session_id, parent_id, agent_id = file_identity(path)
    side = read_sidecar(path) if kind_of_file == "subagent" else {}
    rec = {
        "path": path_str,
        "mtime": int(st.st_mtime),
        "size": st.st_size,
        "session_id": session_id,
        "kind": kind_of_file,
        "parent_id": parent_id,
        "agent_id": agent_id,
        "agent_type": str(side.get("customAgentType") or side.get("agentType") or ""),
        "agent_name": str(side.get("name") or ""),
        "description": str(side.get("description") or ""),
        "model": str(side.get("model") or ""),
        "spawn_depth": int(side.get("spawnDepth") or 0),
        "parent_agent_id": str(side.get("parentAgentId") or ""),
        "tool_use_id": str(side.get("toolUseId") or ""),
        "project": "",
        "branch": "",
        "custom_title": "",
        "ai_title": "",
        "summary": "",
        "first_prompt": "",
        "created": "",
        "modified": "",
        "n_user": 0,
        "n_assistant": 0,
        "n_tool": 0,
        "sidechain": 0,
    }
    # api response id -> (model, in, cache-write 1h, cache-write 5m, cache read, out)
    usage: dict[str, tuple[str, int, int, int, int, int]] = {}
    tail: list[dict] = []
    docs: list[tuple[str, int, str]] = []  # (role, seq, text)
    seq = 0

    try:
        fh = path.open("r", encoding="utf-8", errors="replace")
    except OSError:
        return None

    with fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            kind = d.get("type")

            if kind == "custom-title":
                # the user can rename a session repeatedly; the last one wins
                rec["custom_title"] = d.get("customTitle", "") or rec["custom_title"]
                continue
            if kind == "ai-title":
                rec["ai_title"] = d.get("aiTitle", "") or rec["ai_title"]
                continue
            if kind == "summary":
                rec["summary"] = d.get("summary", "") or rec["summary"]
                continue
            if kind not in ("user", "assistant"):
                continue

            if not rec["project"]:
                rec["project"] = d.get("cwd", "") or ""
            if not rec["branch"]:
                rec["branch"] = d.get("gitBranch", "") or ""
            if d.get("isSidechain"):
                rec["sidechain"] = 1
            ts = d.get("timestamp", "")
            if ts:
                if not rec["created"]:
                    rec["created"] = ts
                rec["modified"] = ts

            msg = d.get("message")
            if not isinstance(msg, dict):
                continue

            parts = message_parts(msg)
            rec["n_tool"] += sum(1 for k, _ in parts if k == "tool")
            text = " ".join(t for k, t in parts if k == "text" and t).strip()

            sender = ""
            if kind == "user":
                rec["n_user"] += 1
                # tool results are echoed as user turns; they are not prompts
                is_tool_echo = bool(parts) and all(
                    k in ("tool_result", "image") for k, _ in parts
                )
                if is_tool_echo:
                    continue
                inbound = inbound_message(text)
                if inbound:
                    # another session talking to this one: never the title, and
                    # only the payload is worth indexing — the rest is boilerplate
                    sender, text = inbound
                else:
                    if text and not rec["first_prompt"]:
                        rec["first_prompt"] = clean_prompt(text)[:300]
                    text = clean_prompt(text)
            else:
                rec["n_assistant"] += 1
                # one api response is written to several adjacent lines carrying
                # the *same* totals (repeated, not streaming deltas), so key the
                # usage by response id and let the last write win. only ids with
                # the `msg_` prefix are api responses: client-side `<synthetic>`
                # placeholders (refusals and the like) carry a bare uuid and a
                # usage object they never actually spent.
                mid = str(msg.get("id") or "")
                u = msg.get("usage")
                if mid.startswith("msg_") and isinstance(u, dict):
                    cw = u.get("cache_creation")
                    if isinstance(cw, dict):
                        # a 1h cache write costs 2x base input and a 5m one
                        # 1.25x, so the two kinds cannot share a bucket
                        w1h = int(cw.get("ephemeral_1h_input_tokens") or 0)
                        w5m = int(cw.get("ephemeral_5m_input_tokens") or 0)
                    else:
                        # no split recorded: price the whole write at the cheaper
                        # ttl rather than dropping it
                        w1h, w5m = 0, int(u.get("cache_creation_input_tokens") or 0)
                    usage[mid] = (
                        str(msg.get("model") or ""),
                        int(u.get("input_tokens") or 0),
                        w1h,
                        w5m,
                        int(u.get("cache_read_input_tokens") or 0),
                        int(u.get("output_tokens") or 0),
                    )

            if text:
                seq += 1
                docs.append((kind, seq, text[:FTS_CHARS]))
                entry = {"role": kind, "text": text[:TAIL_CHARS]}
                if sender:
                    # the list preview labels this line with who sent it instead
                    # of "you" — it is not a turn anyone typed in this session
                    entry["sender"] = sender
                tail.append(entry)
                if len(tail) > TAIL_KEEP:
                    tail.pop(0)

    if not rec["project"]:
        # fall back to the encoded directory name when no message carried a cwd
        try:
            encoded = path.relative_to(PROJECTS).parts[0]
        except ValueError:
            encoded = path.parent.name
        rec["project"] = "/" + encoded.lstrip("-").replace("-", "/")
    rec["tail"] = json.dumps(tail)
    by_model: dict[str, dict[str, int]] = {}
    for model, tin, w1h, w5m, cr, out in usage.values():
        b = by_model.setdefault(
            model, {"in": 0, "cw1h": 0, "cw5m": 0, "cr": 0, "out": 0}
        )
        b["in"] += tin
        b["cw1h"] += w1h
        b["cw5m"] += w5m
        b["cr"] += cr
        b["out"] += out
    rec["usage"] = json.dumps(by_model) if by_model else ""
    # a title the user typed outranks anything generated; for a subagent the
    # sidecar's description is the closest thing to one
    rec["title"] = (
        rec["custom_title"]
        or rec["description"]
        or rec["agent_name"]
        or rec["ai_title"]
        or rec["summary"]
        or rec["first_prompt"]
        or "(empty)"
    )
    rec["day"] = (rec["modified"] or "")[:10]
    rec["_docs"] = docs
    return rec


